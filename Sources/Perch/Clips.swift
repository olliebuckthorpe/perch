import AppKit
import Carbon.HIToolbox
import Observation

/// Something that was copied: a piece of text, or a picture saved to disk.
struct Clip: Identifiable, Equatable {
    let id: String
    var text: String?
    var imagePath: String?
    var at: Date

    var isLink: Bool {
        guard let text, !text.contains(" "), !text.contains("\n") else { return false }
        return text.hasPrefix("http://") || text.hasPrefix("https://")
    }
}

/// A file being held on the shelf until it is wanted somewhere.
struct ShelfItem: Identifiable, Equatable {
    let id: String
    let path: String
    var name: String { URL(fileURLWithPath: path).lastPathComponent }
}

/// The clipboard's recent history and the shelf of held files.
///
/// Anything a password manager marks as secret is never recorded: apps flag those copies and
/// they are skipped. The history lives in `~/.perch`, readable only by this user.
@Observable
final class Clips {
    static let shared = Clips()

    private(set) var history: [Clip] = []
    private(set) var shelf: [ShelfItem] = []

    @ObservationIgnored private var seen = NSPasteboard.general.changeCount
    @ObservationIgnored private var timer: Timer?
    private static let dir = "\(Shell.home)/.perch/clips"
    private static let shelfDir = "\(Shell.home)/.perch/shelf"
    private static let file = "\(Shell.home)/.perch/clips.json"
    private static let secret = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                                 "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]

    func start() {
        for d in [Self.dir, Self.shelfDir] {
            try? FileManager.default.createDirectory(atPath: d, withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
        }
        load()
        timer = Timer.scheduledTimer(withTimeInterval: 0.7, repeats: true) { [weak self] _ in self?.poll() }
        timer?.tolerance = 0.2
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != seen else { return }
        seen = pb.changeCount
        let types = pb.types?.map(\.rawValue) ?? []
        guard !types.contains(where: Self.secret.contains) else { return }
        if let text = pb.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            guard text.count < 60_000 else { return }
            history.removeAll { $0.text == text }
            history.insert(Clip(id: UUID().uuidString, text: text, at: Date()), at: 0)
        } else if let data = pb.data(forType: .png) ?? pb.data(forType: .tiff), let image = NSImage(data: data),
                  let tiff = image.tiffRepresentation, let rep = NSBitmapImageRep(data: tiff),
                  let png = rep.representation(using: .png, properties: [:]) {
            let id = UUID().uuidString
            let path = "\(Self.dir)/\(id).png"
            guard (try? png.write(to: URL(fileURLWithPath: path))) != nil else { return }
            history.insert(Clip(id: id, imagePath: path, at: Date()), at: 0)
        } else {
            return
        }
        trim()
        save()
    }

    private func trim() {
        while history.count > 40 {
            if let path = history.removeLast().imagePath { try? FileManager.default.removeItem(atPath: path) }
        }
    }

    /// Puts a clip back on the clipboard.
    func copy(_ clip: Clip) {
        let pb = NSPasteboard.general
        pb.clearContents()
        if let text = clip.text {
            pb.setString(text, forType: .string)
        } else if let path = clip.imagePath, let image = NSImage(contentsOfFile: path) {
            pb.writeObjects([image])
        }
        // Perch's own write is not a new copy.
        seen = pb.changeCount
        if let i = history.firstIndex(of: clip), i > 0 {
            history.remove(at: i)
            history.insert(clip, at: 0)
            save()
        }
    }

    /// Copies a clip and pastes it into whatever app was being used, as if Cmd+V had been pressed.
    /// Pressing the keys for the user needs the Accessibility permission; without it the clip is
    /// simply on the clipboard, ready to paste by hand.
    func paste(_ clip: Clip) {
        let ui = NotchUI.shared
        // Opened beside a chat: the clip goes into that chat's reply, not into another app.
        if ui.clipsInline, let id = ui.selectedID {
            if let text = clip.text {
                let draft = ui.drafts[id] ?? ""
                ui.drafts[id] = draft.isEmpty ? text : "\(draft) \(text)"
            } else if let path = clip.imagePath, let file = Attachment.from(file: URL(fileURLWithPath: path)) {
                ui.attachments[id, default: []].append(file)
            }
            ui.closeClips()
            return
        }
        copy(clip)
        ui.collapse()
        guard AXIsProcessTrusted() else { return }
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.18) {
            let source = CGEventSource(stateID: .combinedSessionState)
            for down in [true, false] {
                let event = CGEvent(keyboardEventSource: source, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: down)
                event?.flags = .maskCommand
                event?.post(tap: .cgAnnotatedSessionEventTap)
            }
        }
    }

    func remove(_ clip: Clip) {
        history.removeAll { $0.id == clip.id }
        if let path = clip.imagePath { try? FileManager.default.removeItem(atPath: path) }
        save()
    }

    func clearHistory() {
        for clip in history { if let path = clip.imagePath { try? FileManager.default.removeItem(atPath: path) } }
        history = []
        save()
    }

    // MARK: Shelf

    /// Holds files where they already are: the shelf remembers them, it does not move them.
    func hold(_ urls: [URL]) {
        for url in urls where url.isFileURL && !shelf.contains(where: { $0.path == url.path }) {
            shelf.insert(ShelfItem(id: UUID().uuidString, path: url.path), at: 0)
        }
        save()
    }

    /// A picture dragged from somewhere that has no file of its own (a web page, say).
    func hold(_ image: NSImage) {
        guard let tiff = image.tiffRepresentation, let rep = NSBitmapImageRep(data: tiff),
              let png = rep.representation(using: .png, properties: [:]) else { return }
        let f = DateFormatter()
        f.dateFormat = "HH.mm.ss"
        let path = "\(Self.shelfDir)/Image \(f.string(from: Date())).png"
        guard (try? png.write(to: URL(fileURLWithPath: path))) != nil else { return }
        hold([URL(fileURLWithPath: path)])
    }

    func drop(_ item: ShelfItem) {
        shelf.removeAll { $0.id == item.id }
        if item.path.hasPrefix(Self.shelfDir) { try? FileManager.default.removeItem(atPath: item.path) }
        save()
    }

    // MARK: Saving

    private func save() {
        let rows: [String: Any] = [
            "history": history.map { ["id": $0.id, "text": $0.text ?? "", "image": $0.imagePath ?? "", "at": $0.at.timeIntervalSince1970] as [String: Any] },
            "shelf": shelf.map { ["id": $0.id, "path": $0.path] },
        ]
        guard let data = try? JSONSerialization.data(withJSONObject: rows) else { return }
        FileManager.default.createFile(atPath: Self.file, contents: data, attributes: [.posixPermissions: 0o600])
    }

    private func load() {
        guard let data = FileManager.default.contents(atPath: Self.file),
              let rows = try? JSONSerialization.jsonObject(with: data) as? [String: Any] else { return }
        let fm = FileManager.default
        history = (rows["history"] as? [[String: Any]] ?? []).compactMap { r in
            guard let id = r["id"] as? String else { return nil }
            let text = r["text"] as? String ?? "", image = r["image"] as? String ?? ""
            if text.isEmpty, image.isEmpty || !fm.fileExists(atPath: image) { return nil }
            return Clip(id: id, text: text.isEmpty ? nil : text, imagePath: image.isEmpty ? nil : image,
                        at: Date(timeIntervalSince1970: r["at"] as? Double ?? 0))
        }
        shelf = (rows["shelf"] as? [[String: String]] ?? []).compactMap { r in
            guard let id = r["id"], let path = r["path"], fm.fileExists(atPath: path) else { return nil }
            return ShelfItem(id: id, path: path)
        }
    }
}

/// System-wide keyboard shortcuts. These work from any app and need no permission.
final class Hotkeys {
    static let shared = Hotkeys()
    private var actions: [UInt32: () -> Void] = [:]
    private var installed = false

    func register(key: Int, modifiers: Int, action: @escaping () -> Void) {
        if !installed {
            installed = true
            var spec = EventTypeSpec(eventClass: OSType(kEventClassKeyboard), eventKind: UInt32(kEventHotKeyPressed))
            InstallEventHandler(GetApplicationEventTarget(), { _, event, _ in
                var id = EventHotKeyID()
                GetEventParameter(event, EventParamName(kEventParamDirectObject), EventParamType(typeEventHotKeyID), nil,
                                  MemoryLayout<EventHotKeyID>.size, nil, &id)
                let which = id.id
                DispatchQueue.main.async { Hotkeys.shared.actions[which]?() }
                return noErr
            }, 1, &spec, nil, nil)
        }
        let id = UInt32(actions.count + 1)
        actions[id] = action
        var ref: EventHotKeyRef?
        RegisterEventHotKey(UInt32(key), UInt32(modifiers), EventHotKeyID(signature: OSType(0x50524348), id: id),
                            GetApplicationEventTarget(), 0, &ref)
    }
}
